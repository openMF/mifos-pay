// Cloudflare Pages worker for the web app (Pages "advanced mode": a _worker.js at the root of the
// deployed directory handles every request; other hosts serve it as an inert file). Template-owned:
// configure it through app-profile/app.yaml#network.web_cors, never by editing this file.
//
// 1. <relay>/?<https-url> (relay `/cors` by default) — the app's own CORS relay. In `web_cors.mode:
//    relay` the web build routes every request to an allowlisted host here, so the browser only talks
//    to this origin and the upstream server's CORS policy never applies. Every method is forwarded with
//    its body. The allowlist is relay-allowlist.json (GENERATED by syncForkConfig beside this file:
//    every access point's host + web_cors.hosts; `*.example.com` = its subdomains), plus the optional
//    PROXY_ALLOWED_HOSTS Pages variable (comma-separated). Anything else is 403 — never an open proxy.
//    Origin, Referer, cookies and client-IP headers never leave; Set-Cookie never comes back. Every
//    relay answer carries X-Kpt-Relay: 1; a /cors response without it means no worker, and the app
//    then calls the server directly.
// 2. Everything else is the static site, served with COOP + COEP so the page is cross-origin isolated
//    and the app's SQLite database persists (OPFS). In advanced mode Pages does not apply _headers, so
//    the worker sets them itself.

const ISOLATION_HEADERS = {
  "Cross-Origin-Opener-Policy": "same-origin",
  "Cross-Origin-Embedder-Policy": "require-corp",
};
const METHODS = ["GET", "HEAD", "POST", "PUT", "PATCH", "DELETE"];
// Request headers that identify the browser or this hop, not the API call.
const DROP_REQUEST = new Set(["origin", "referer", "cookie", "host", "connection", "content-length", "x-real-ip"]);
const MAX_REDIRECTS = 5;
const RELAY_HEADER = "X-Kpt-Relay"; // core-base/network CORS_RELAY_HEADER

let configPromise; // per isolate: the deployed relay-allowlist.json never changes within a deployment

export default {
  async fetch(request, env) {
    const url = new URL(request.url);
    const config = await loadConfig(request, env);
    if (url.pathname === config.relayPath || url.pathname === config.relayPath + "/") {
      // EVERY relay answer is tagged — errors included — so the app can tell "the worker refused" (final)
      // from "no worker here" (a static host's 404 page: the app falls back to calling directly).
      // A page this site serves from elsewhere (allowedOrigins — e.g. a GitHub Pages copy, which cannot
      // run this worker) calls the relay cross-origin: answer its preflight and let it read the reply.
      const cors = corsHeaders(request, config);
      let response;
      try {
        response = request.method === "OPTIONS" && cors ? new Response(null, { status: 204 }) : await relay(request, config, url);
      } catch {
        response = new Response("Upstream unreachable", { status: 502 });
      }
      response.headers.set(RELAY_HEADER, "1");
      if (cors) {
        for (const [name, value] of Object.entries(cors)) response.headers.set(name, value);
        response.headers.set("Cross-Origin-Resource-Policy", "cross-origin");
      }
      return response;
    }
    const asset = await env.ASSETS.fetch(request);
    const response = new Response(asset.body, asset);
    for (const [name, value] of Object.entries(ISOLATION_HEADERS)) response.headers.set(name, value);
    return response;
  },
};

function loadConfig(request, env) {
  if (!configPromise) {
    configPromise = (async () => {
      let file = {};
      try {
        const res = await env.ASSETS.fetch(new Request(new URL("/relay-allowlist.json", request.url)));
        if (res.ok) file = await res.json();
        else configPromise = undefined; // missing/failed: relay nothing now, retry on the next request
      } catch {
        configPromise = undefined;
      }
      const fromEnv = (env.PROXY_ALLOWED_HOSTS || "").split(",").map((h) => h.trim()).filter(Boolean);
      const hosts = [...(Array.isArray(file.hosts) ? file.hosts : []), ...fromEnv].map((h) => String(h).toLowerCase());
      // An external relay (https://…) or direct mode leaves this site's own relay path at the default.
      const relayPath = typeof file.relay === "string" && /^\/[A-Za-z0-9_-]+$/.test(file.relay) ? file.relay : "/cors";
      const origins = (Array.isArray(file.allowedOrigins) ? file.allowedOrigins : []).map((o) => String(o).toLowerCase());
      return { hosts, relayPath, origins };
    })();
  }
  return configPromise;
}

// CORS for a page served from one of config.origins, or null for any other (incl. same-origin) caller.
function corsHeaders(request, config) {
  const origin = (request.headers.get("Origin") || "").toLowerCase();
  if (!origin || !config.origins.includes(origin)) return null;
  return {
    "Access-Control-Allow-Origin": request.headers.get("Origin"),
    "Access-Control-Allow-Methods": METHODS.join(", "),
    "Access-Control-Allow-Headers": request.headers.get("Access-Control-Request-Headers") || "*",
    "Access-Control-Expose-Headers": RELAY_HEADER, // the app reads the tag to know the relay answered
    "Access-Control-Max-Age": "86400",
    Vary: "Origin",
  };
}

function allowed(hostname, hosts) {
  const h = hostname.toLowerCase();
  return hosts.some((p) => (p.startsWith("*.") ? h.endsWith(p.slice(1)) : h === p));
}

async function relay(request, config, url) {
  if (request.method === "OPTIONS") return new Response(null, { status: 204 }); // same-origin: never needed
  if (!METHODS.includes(request.method)) {
    return new Response("Method not allowed", { status: 405, headers: { Allow: METHODS.join(", ") } });
  }
  let target;
  try {
    target = new URL(url.search.slice(1)); // everything after the first "?" is the target URL, verbatim
  } catch {
    return new Response("Expected <relay>/?<https-url>", { status: 400 });
  }
  if (target.protocol !== "https:" || target.port !== "" || !allowed(target.hostname, config.hosts)) {
    return new Response("Host not allowed", { status: 403 });
  }

  const headers = new Headers();
  for (const [name, value] of request.headers) {
    const n = name.toLowerCase();
    if (DROP_REQUEST.has(n) || n.startsWith("cf-") || n.startsWith("x-forwarded-")) continue;
    headers.set(name, value);
  }
  const authed = headers.has("authorization");
  let method = request.method;
  let body = method === "GET" || method === "HEAD" ? undefined : await request.arrayBuffer();

  // Redirects are followed HERE, one hop at a time, so every hop is re-checked against the allowlist —
  // `redirect: "follow"` would let an allowlisted host bounce the relay anywhere. A hop to another host
  // loses Authorization (as a browser would); 303, or 301/302 after a POST, continues as a bodyless GET.
  let upstream;
  for (let hop = 0; ; hop++) {
    upstream = await fetch(target, { method, headers, body, redirect: "manual" });
    const location = upstream.headers.get("Location");
    if (upstream.status < 300 || upstream.status > 399 || upstream.status === 304 || !location) break;
    const next = new URL(location, target);
    if (hop >= MAX_REDIRECTS || next.protocol !== "https:" || next.port !== "" || !allowed(next.hostname, config.hosts)) {
      return new Response("Redirect target not allowed", { status: 502 });
    }
    if (next.host !== target.host) headers.delete("authorization");
    if (upstream.status === 303 || ((upstream.status === 301 || upstream.status === 302) && method === "POST")) {
      method = "GET";
      body = undefined;
      headers.delete("content-type");
    }
    target = next;
  }

  const response = new Response(upstream.body, upstream);
  response.headers.delete("Set-Cookie");
  response.headers.set("Cross-Origin-Resource-Policy", "same-origin");
  if (authed) response.headers.set("Cache-Control", "no-store");
  return response;
}
