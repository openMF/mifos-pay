// module-deps.gradle.kts — the FORK-OWNED dependency seam for `core/network` (white-label).
//
// `core/network/build.gradle.kts` is template-owned and FULL-COPIES on
// `/kmp-project-template-sync`. This fork's own dependencies live HERE so they survive every sync.
//
// String configuration notation is required — type-safe `libs.`/`projects.`/`compose.` accessors
// are not generated for applied script plugins.

// Fork plugins: this module's fork code uses Compose resources (`Res` / StringResource), so it needs the
// Compose + Compose-compiler plugins. They lived in the template-owned build.gradle.kts plugins {} block,
// which a sync full-copies; apply(plugin = …) here survives it (moved at the 90ff6da6 template sync).
apply(plugin = "org.jetbrains.compose")
apply(plugin = "org.jetbrains.kotlin.plugin.compose")
// generateResClass=auto skips the Res class when the resources dependency is declared through this seam rather
// than the build file, so force it: fork code imports <module>.generated.resources.Res.
// Plugin classes are not on a script plugin's classpath, so go through the Groovy builder (string → enum coerced).
extensions.getByName("compose").withGroovyBuilder {
    getProperty("resources").withGroovyBuilder { setProperty("generateResClass", "Always") }
}

val libs = extensions.getByType<org.gradle.api.artifacts.VersionCatalogsExtension>().named("libs")

dependencies {
    // Moved out of commonMain.dependencies in build.gradle.kts (template-owned, full-copied).
    "commonMainImplementation"(libs.findLibrary("jb-composeRuntime").get())
    "commonMainImplementation"(libs.findLibrary("jb-composeComponentsResources").get())
}

// ── Fork: mifos-pay Supabase instance-config credentials ─────────────────────────────────────────
// The template retired SupabaseConfigConventionPlugin (single-project credentials) in favour of
// app-profile access points; mifos-pay's InstanceConfigLoader still bootstraps from ONE Supabase project
// whose {url, anonKey} live in the vault-backed `supabase_credentials` secret (secrets/fork-layout.yaml).
// This regenerates the same `kpt.core.network.config.SupabaseCredentials` object the plugin emitted. The
// path comes from the one resolver's output map (gradle/secrets-paths.properties), never hardcoded.
val supabaseGeneratedDir = layout.buildDirectory.dir("generated/supabase")
val supabaseCredentialsFile: File = run {
    val map = rootProject.file("gradle/secrets-paths.properties")
    val rel = if (map.isFile) java.util.Properties().apply { map.inputStream().use(::load) }.getProperty("supabase_credentials") else null
    if (rel.isNullOrBlank()) rootProject.file("build/secrets-unresolved/supabase_credentials") else rootProject.file(rel.trim())
}
val generateSupabaseConfig = tasks.register("generateSupabaseConfig") {
    val content = providers.fileContents(objects.fileProperty().fileValue(supabaseCredentialsFile)).asText.orElse("")
    inputs.property("credentialsContent", content)
    val out = supabaseGeneratedDir.map { it.file("kpt/core/network/config/SupabaseCredentials.kt") }
    outputs.file(out)
    doLast {
        val text = content.get()
        fun field(name: String) = Regex("\"$name\"\\s*:\\s*\"([^\"]*)\"").find(text)?.groupValues?.get(1).orEmpty()
        if (text.isBlank()) logger.warn("supabase_credentials not materialized — run `/secrets pull`; the instance config will be empty")
        val f = out.get().asFile
        f.parentFile.mkdirs()
        f.writeText(
            """
            |package kpt.core.network.config
            |
            |/** GENERATED by core/network/module-deps.gradle.kts from the `supabase_credentials` secret. DO NOT EDIT. */
            |object SupabaseCredentials {
            |    const val url: String = "${field("url")}"
            |    const val anonKey: String = "${field("anonKey")}"
            |}
            |
            """.trimMargin(),
        )
    }
}
val kmpSourceSets = extensions.getByName("kotlin").withGroovyBuilder { getProperty("sourceSets") } as NamedDomainObjectContainer<*>
(kmpSourceSets.getByName("commonMain").withGroovyBuilder { getProperty("kotlin") } as SourceDirectorySet)
    .srcDir(generateSupabaseConfig.map { supabaseGeneratedDir.get() })
