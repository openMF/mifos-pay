package kpt.core.model.config

/**
 * The fork's own named organisation links — a community chat, a product site, a status page —
 * for whatever surface the fork builds (an About screen, a help sheet).
 *
 * **SoT: `app-profile/app.yaml#org.links`** (`name: url`). The map below is GENERATED by
 * `./gradlew syncForkConfig`; change the YAML, not this file. The template ships none, and nothing in
 * the template reads a name — the links exist for the fork's own screens, which is why this is a
 * free-form map rather than one fixed key per link. The org links the TEMPLATE does use keep their own
 * keys (`org.privacy_url`, `org.support_url`, `org.marketing_url`).
 *
 * ```
 * AppOrgLinks["community"]?.let { url -> LinkRow("Community", url) }
 * ```
 */
object AppOrgLinks {
    // syncForkConfig:org-links:begin — GENERATED from app-profile/app.yaml#org.links. Do not hand-edit.
    private val links: Map<String, String> = emptyMap()
    // syncForkConfig:org-links:end

    /** The URL declared under `org.links.<name>`, or null when the fork declares none by that name. */
    operator fun get(name: String): String? = links[name]

    /** Every declared link, in app-profile order. */
    val all: Map<String, String> get() = links
}
