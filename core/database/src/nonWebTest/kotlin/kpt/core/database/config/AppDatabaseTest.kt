package kpt.core.database.config

import kpt.core.database.AppDatabase
import kpt.core.database.di.testPlatformModule
import org.koin.core.context.startKoin
import org.koin.core.context.stopKoin
import org.koin.mp.KoinPlatform
import kotlin.test.AfterTest
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertNotNull

class AppDatabaseTest {

    private var database: AppDatabase? = null

    @AfterTest
    fun teardown() {
        // stopKoin() must run even when a test failed before building, or the first fault leaks a
        // started Koin and every later test dies with KoinApplicationAlreadyStartedException —
        // one real failure reported as four.
        runCatching { database?.close() }
        stopKoin()
    }

    @Test
    fun inMemoryDatabaseCanBeCreated() {
        startKoin { modules(testPlatformModule) }
        database = KoinPlatform.getKoin().get()

        assertNotNull(database)
    }

    @Test
    fun databaseVersionIsTheForksDeclaredVersion() {
        // Pins the database-ksp wiring: the generated AppDatabase.VERSION derives from the fork-owned
        // ForkDatabaseConfig.VERSION, the one constant a fork bumps. The template's own v13 schema is
        // pinned in alerts/DemoDatabaseTest.
        assertEquals(ForkDatabaseConfig.VERSION, AppDatabase.VERSION)
    }

    @Test
    fun databaseNameIsCorrect() {
        // Fork-unique, appId-derived (regenerated by syncForkConfig). DATABASE_NAME
        // delegates to the single source of truth, DatabaseConfig.NAME.
        assertEquals(DatabaseConfig.NAME, AppDatabase.DATABASE_NAME)
    }
}
