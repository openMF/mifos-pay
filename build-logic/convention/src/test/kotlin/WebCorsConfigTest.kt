import org.gradle.api.GradleException
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertFailsWith
import kotlin.test.assertNull
import kotlin.test.assertTrue

/** `network.web_cors` → the policy + `relay-allowlist.json` syncForkConfig generates. */
class WebCorsConfigTest {

    private val points = listOf(
        mapOf("id" to "fineract", "base_url" to "https://Bank.Mifos.Community/"),
        mapOf("id" to "fred", "base_url" to "https://api.stlouisfed.org/", "proxied_host" to "api.stlouisfed.org"),
        mapOf("id" to "legacy", "base_url" to "https://a.test/", "proxied_host" to "cdn.a.test"),
    )

    private fun net(vararg extra: Pair<String, Any?>) = mapOf("access_points" to points) + extra

    @Test
    fun absentBlockIsRelayThroughCorsWithEveryPointHost() {
        val c = parseWebCors(net())
        assertEquals("relay", c.mode)
        assertEquals("/cors", c.relay)
        assertEquals(listOf("bank.mifos.community", "api.stlouisfed.org", "a.test", "cdn.a.test"), c.allowlist)
        assertTrue(c.warnings.isEmpty())
    }

    @Test
    fun extraHostsAndWildcardsAreAppended() {
        val c = parseWebCors(net("web_cors" to mapOf("relay" to "https://relay.example.com/cors", "hosts" to listOf("*.Example.com", "x.io"))))
        assertEquals("https://relay.example.com/cors", c.relay)
        assertEquals(listOf("*.example.com", "x.io"), c.allowlist.takeLast(2))
    }

    @Test
    fun directModeRelaysNothing() {
        val c = parseWebCors(net("web_cors" to mapOf("mode" to "direct", "hosts" to listOf("x.io"))))
        assertEquals("direct", c.mode)
        assertNull(c.relay)
        assertEquals(emptyList(), c.allowlist)
    }

    @Test
    fun invalidValuesFailTheSync() {
        fun bad(block: Map<String, Any?>) = assertFailsWith<GradleException> { parseWebCors(net("web_cors" to block)) }
        bad(mapOf("mode" to "proxy"))
        bad(mapOf("relay" to "http://relay.example.com"))
        bad(mapOf("relay" to "cors"))
        bad(mapOf("relay" to null))
        bad(mapOf("relay" to "none"))
        listOf("*", "https://x.io", "x.io/path", "x.io:8443", "*.com", "a..b").forEach { bad(mapOf("hosts" to listOf(it))) }
    }

    @Test
    fun allowedOriginsLetAnotherSiteUseThisRelay() {
        // The app is also served from a static host (GitHub Pages) that cannot run the worker, so that
        // copy uses this site's relay cross-origin — the worker must answer CORS for exactly that origin.
        val c = parseWebCors(net("web_cors" to mapOf("allowed_origins" to listOf("https://Org.GitHub.io/"))))
        assertEquals(listOf("https://org.github.io"), c.allowedOrigins)
        assertTrue(relayAllowlistJson(c).contains("\"allowedOrigins\": [\n    \"https://org.github.io\"\n  ]"))
        assertTrue(relayAllowlistJson(parseWebCors(net())).contains("\"allowedOrigins\": []"))
        listOf("http://org.github.io", "org.github.io", "https://*.github.io", "https://org.github.io/app").forEach {
            assertFailsWith<GradleException> { parseWebCors(net("web_cors" to mapOf("allowed_origins" to listOf(it)))) }
        }
    }

    @Test
    fun legacyKeyIsMigratedWithAWarning() {
        val c = parseWebCors(net("web_cors_proxy" to "https://old.relay.io"))
        assertEquals("relay", c.mode)
        assertEquals("https://old.relay.io", c.relay)
        assertTrue(c.warnings.single().contains("deprecated"))
        assertEquals("direct", parseWebCors(net("web_cors_proxy" to "none")).mode)
        // Both present: the new block wins and the old key is called out.
        val both = parseWebCors(net("web_cors_proxy" to "https://old.relay.io", "web_cors" to mapOf("mode" to "relay")))
        assertEquals("/cors", both.relay)
        assertTrue(both.warnings.single().contains("ignored"))
    }

    @Test
    fun generatedJsonCarriesTheListAndASentinel() {
        val json = relayAllowlistJson(parseWebCors(net("web_cors" to mapOf("hosts" to listOf("*.example.com")))))
        assertTrue(json.contains("\"_generated\": \"GENERATED by syncForkConfig"), json)
        assertTrue(json.contains("\"mode\": \"relay\"") && json.contains("\"relay\": \"/cors\""), json)
        assertTrue(json.contains("\"*.example.com\"") && json.contains("\"bank.mifos.community\""), json)
        val direct = relayAllowlistJson(parseWebCors(net("web_cors" to mapOf("mode" to "direct"))))
        assertTrue(direct.contains("\"relay\": null") && direct.contains("\"hosts\": []"), direct)
    }
}
